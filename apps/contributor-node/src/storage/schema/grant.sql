CREATE TABLE IF NOT EXISTS grant (
  id TEXT PRIMARY KEY,
  node_id TEXT NOT NULL,
  owner_id TEXT NOT NULL,
  team_id TEXT NOT NULL,
  workspace_id TEXT NOT NULL,
  run_id TEXT NOT NULL,
  purpose_digest TEXT NOT NULL,
  resource_id TEXT NOT NULL,
  resource_digest TEXT NOT NULL,
  operations TEXT NOT NULL CHECK (json_valid(operations)),
  requester_ids TEXT NOT NULL CHECK (json_valid(requester_ids)),
  recipient_rules TEXT NOT NULL CHECK (json_valid(recipient_rules)),
  rights TEXT NOT NULL CHECK (json_valid(rights)),
  not_before TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  usage_limit INTEGER NOT NULL CHECK (usage_limit >= 1),
  budget TEXT NOT NULL CHECK (json_valid(budget)),
  cache_policy TEXT NOT NULL CHECK (json_valid(cache_policy)),
  handoff_policy TEXT NOT NULL,
  policy_revision INTEGER NOT NULL CHECK (policy_revision >= 1),
  owner_signature TEXT NOT NULL,
  state TEXT NOT NULL CHECK (state IN ('pending', 'active', 'rejected', 'revoked', 'expired'))
);
